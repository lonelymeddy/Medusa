import { NextRequest, NextResponse } from 'next/server';
import { cybersecurityStorage } from '@/lib/cybersecurity/storage';

export async function GET(req: NextRequest) {
  const { searchParams } = new URL(req.url);
  const id = searchParams.get('id');

  if (!id) {
    return NextResponse.json({ success: false, error: 'Missing investigation id' }, { status: 400 });
  }

  const inv = cybersecurityStorage.get(id);
  if (!inv) {
    return NextResponse.json({ success: false, error: 'Investigation not found' }, { status: 404 });
  }

  const findingsText = inv.findings
    .map(
      (f, idx) =>
        `### Finding ${idx + 1}: ${f.title}\n- **Severity**: ${f.severity}\n- **Category**: ${f.category}\n- **Asset**: \`${f.affectedAsset}\`\n- **Description**: ${f.description}\n- **Evidence**: \`${f.evidence}\`\n- **Impact**: ${f.potentialImpact}\n- **Remediation**: ${f.remediation}\n`
    )
    .join('\n');

  const report = `
# MEDUSA CYBERSECURITY AUDIT REPORT
**Target**: ${inv.target || 'General Scope'}
**Assessment Date**: ${new Date(inv.createdAt).toUTCString()}
**Audit Status**: ${inv.status.toUpperCase()}
**Findings Discovered**: ${inv.findings.length}

---

## EXECUTIVE SUMMARY
${inv.reportMarkdown || 'Autonomous assessment completed across designated attack surfaces.'}

---

## DETAILED FINDINGS
${findingsText || 'No vulnerabilities identified within current authorized boundary.'}

---
*Generated by MEDUSA Autonomous AI Cybersecurity Platform*
`;

  return new NextResponse(report, {
    status: 200,
    headers: {
      'Content-Type': 'text/markdown; charset=utf-8',
      'Content-Disposition': `attachment; filename="medusa-security-report-${id}.md"`,
    },
  });
}
