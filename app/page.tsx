"use client";

import React, { useState, useEffect } from "react";
import { RepoSelector } from "@/components/RepoSelector";
import { TaskPromptBar } from "@/components/TaskPromptBar";
import { PlanChecklist } from "@/components/PlanChecklist";
import { LiveTerminal } from "@/components/LiveTerminal";
import { GitDiffViewer } from "@/components/GitDiffViewer";
import { TelemetryPanel } from "@/components/TelemetryPanel";
import { JulesSession, PlanStep, JulesLogEntry } from "@/lib/jules-engine/types";
import { Cpu, Terminal, GitBranch, Shield, Zap, Sparkles, CheckCircle2 } from "lucide-react";

export default function WorkspacePage() {
  const [repoUrl, setRepoUrl] = useState("https://github.com/facebook/react");
  const [taskPrompt, setTaskPrompt] = useState("Fix failing edge cases in request processing");
  const [currentSession, setCurrentSession] = useState<JulesSession | null>(null);
  const [isRunning, setIsRunning] = useState(false);
  const [isSubmittingPR, setIsSubmittingPR] = useState(false);

  // Initialize session on mount or url change
  useEffect(() => {
    initSession();
  }, [repoUrl]);

  const initSession = async () => {
    try {
      const res = await fetch("/api/jules/sessions", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ repoUrl, taskPrompt }),
      });
      const data = await res.json();
      if (data.success) {
        setCurrentSession(data.session);
      }
    } catch (err) {
      console.error("Failed to initialize session", err);
    }
  };

  const handleStartAgent = async (autoRun: boolean) => {
    if (!currentSession) return;
    setIsRunning(true);

    try {
      const res = await fetch("/api/jules/run", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          sessionId: currentSession.id,
          autoRunAll: autoRun,
        }),
      });
      const data = await res.json();
      if (data.success && data.session) {
        setCurrentSession(data.session);
      }
    } catch (err) {
      console.error("Error executing Jules agent run", err);
    } finally {
      setIsRunning(false);
    }
  };

  const handleSubmitPR = async () => {
    if (!currentSession) return;
    setIsSubmittingPR(true);

    try {
      const res = await fetch("/api/jules/submit", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          sessionId: currentSession.id,
          title: taskPrompt,
          description: `Autonomous bug fix and verification generated by Jules Agent.`,
        }),
      });
      const data = await res.json();
      if (data.success && data.session) {
        setCurrentSession(data.session);
      }
    } catch (err) {
      console.error("Error submitting PR", err);
    } finally {
      setIsSubmittingPR(false);
    }
  };

  return (
    <div className="flex-1 flex flex-col p-4 md:p-6 max-w-7xl mx-auto w-full gap-5">
      {/* Top Banner / System Telemetry */}
      <div className="flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3 border-b border-[#1b263b] pb-4">
        <div>
          <h1 className="text-jules-xl font-bold tracking-tight text-white flex items-center gap-2">
            <span>Jules Autonomous Coding Workspace</span>
          </h1>
          <p className="text-jules-sm text-slate-400 mt-0.5">
            Polyglot autonomous agent that reproduces bugs, formulates merge diffs, verifies regression tests, and submits PRs.
          </p>
        </div>

        <div className="flex items-center gap-2">
          <div className="px-3 py-1 rounded bg-[#0f172a] border border-[#1e293b] text-jules-micro font-mono text-slate-300 flex items-center gap-2">
            <span className="w-2 h-2 rounded-full bg-emerald-400 animate-pulse" />
            <span>Target Branch: <strong className="text-blue-400">main</strong></span>
          </div>
          {currentSession?.newBranch && (
            <div className="px-3 py-1 rounded bg-[#0f172a] border border-[#1e293b] text-jules-micro font-mono text-slate-300 flex items-center gap-2">
              <GitBranch className="w-3.5 h-3.5 text-blue-400" />
              <span>{currentSession.newBranch}</span>
            </div>
          )}
        </div>
      </div>

      {/* Target Repo & Prompt Bar */}
      <div className="grid grid-cols-1 lg:grid-cols-3 gap-4">
        <div className="lg:col-span-1 flex flex-col gap-2">
          <label className="text-jules-sm font-medium text-slate-300 flex items-center gap-1.5">
            <GitBranch className="w-3.5 h-3.5 text-blue-400" />
            <span>Target Repository</span>
          </label>
          <RepoSelector
            selectedUrl={repoUrl}
            onSelectUrl={(url) => setRepoUrl(url)}
            isLoading={isRunning}
          />
        </div>

        <div className="lg:col-span-2">
          <TaskPromptBar
            prompt={taskPrompt}
            onPromptChange={setTaskPrompt}
            onStartAgent={handleStartAgent}
            isRunning={isRunning}
          />
        </div>
      </div>

      {/* Main Execution Arena */}
      <div className="grid grid-cols-1 lg:grid-cols-12 gap-5 flex-1 min-h-[500px]">
        {/* Left Column: Plan Checklist */}
        <div className="lg:col-span-4 flex flex-col gap-4">
          <PlanChecklist
            plan={currentSession?.plan || []}
            currentStepIndex={currentSession?.currentStepIndex || 0}
          />

          <TelemetryPanel
            testResults={currentSession?.testResults}
          />
        </div>

        {/* Right Column: Split Live Reasoner & Git Diffs */}
        <div className="lg:col-span-8 flex flex-col gap-4">
          <div className="h-[280px]">
            <LiveTerminal
              logs={currentSession?.logs || []}
              isRunning={isRunning}
            />
          </div>

          <div className="flex-1 min-h-[320px]">
            <GitDiffViewer
              diffs={currentSession?.diffs || []}
              prUrl={currentSession?.prUrl}
              branchName={currentSession?.newBranch}
              onSubmitPR={handleSubmitPR}
              isSubmitting={isSubmittingPR}
            />
          </div>
        </div>
      </div>
    </div>
  );
}
