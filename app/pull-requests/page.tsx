"use client";

import React, { useState, useEffect } from "react";
import Link from "next/link";
import {
  GitPullRequest,
  ExternalLink,
  CheckCircle2,
  Clock,
  GitBranch,
  Layers,
  FileCode,
  Loader2,
} from "lucide-react";
import { PullRequestRecord } from "@/lib/jules-engine/types";
import { formatTimestamp, cn } from "@/lib/utils";

export default function PullRequestsPage() {
  const [prs, setPrs] = useState<PullRequestRecord[]>([]);
  const [isLoading, setIsLoading] = useState(true);

  useEffect(() => {
    fetch("/api/jules/pull-requests")
      .then((res) => res.json())
      .then((data) => {
        if (data.success) {
          setPrs(data.prs || []);
        }
      })
      .finally(() => setIsLoading(false));
  }, []);

  return (
    <div className="flex-1 p-4 sm:p-6 lg:p-8 max-w-7xl mx-auto w-full space-y-6">
      <div className="border-b border-[#162238] pb-4">
        <h1 className="text-xl font-bold text-white flex items-center gap-2">
          <GitPullRequest className="w-5 h-5 text-cyan-400" />
          <span>Pull Requests Generated by Medusa</span>
        </h1>
        <p className="text-xs text-slate-400 mt-1">
          Review, track, and inspect PRs created with targeted Git merge diffs and automated verifications.
        </p>
      </div>

      {isLoading ? (
        <div className="py-20 flex flex-col items-center justify-center text-slate-400">
          <Loader2 className="w-8 h-8 animate-spin text-cyan-400 mb-2" />
          <span className="text-xs font-mono">Loading pull requests...</span>
        </div>
      ) : prs.length === 0 ? (
        <div className="p-12 text-center bg-[#090d16] border border-[#162238] rounded-2xl space-y-3">
          <GitPullRequest className="w-10 h-10 text-slate-600 mx-auto" />
          <h3 className="text-sm font-semibold text-slate-300">No pull requests created yet</h3>
          <p className="text-xs text-slate-500 max-w-md mx-auto">
            When you complete an autonomous task in the Workspace, submit the verified change to generate a PR record here.
          </p>
          <Link
            href="/workspace"
            className="inline-flex items-center gap-1.5 px-4 py-2 rounded-lg bg-blue-600 hover:bg-blue-500 text-white text-xs font-semibold"
          >
            Go to Workspace
          </Link>
        </div>
      ) : (
        <div className="grid grid-cols-1 gap-3">
          {prs.map((pr) => (
            <div
              key={pr.id}
              className="p-4 bg-[#090d16] border border-[#162238] hover:border-[#22334f] rounded-xl transition-all flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4"
            >
              <div className="space-y-1.5 flex-1 min-w-0">
                <div className="flex items-center gap-2 flex-wrap">
                  <span className="font-mono text-xs font-semibold text-cyan-300">
                    {pr.repoUrl.replace("https://github.com/", "")}
                  </span>
                  <span className="text-[10px] font-mono px-2 py-0.5 rounded uppercase font-semibold bg-emerald-500/10 text-emerald-400 border border-emerald-500/20">
                    {pr.status}
                  </span>
                  <span className="text-[10px] font-mono text-slate-500">
                    {formatTimestamp(pr.createdAt)}
                  </span>
                </div>

                <h3 className="text-sm font-semibold text-white truncate">{pr.title}</h3>

                <div className="flex items-center gap-4 text-xs font-mono text-slate-400 flex-wrap">
                  <span className="flex items-center gap-1">
                    <GitBranch className="w-3.5 h-3.5 text-blue-400" />
                    {pr.branch} &rarr; {pr.targetBranch}
                  </span>
                  <span>•</span>
                  <span className="text-emerald-400">+{pr.diffStats?.additions || 0}</span>
                  <span className="text-rose-400">-{pr.diffStats?.deletions || 0}</span>
                  <span>•</span>
                  <span>{pr.diffStats?.filesCount || 0} files</span>
                </div>
              </div>

              <div className="flex items-center gap-2 shrink-0">
                <a
                  href={pr.prUrl}
                  target="_blank"
                  rel="noreferrer"
                  className="flex items-center gap-1.5 px-3.5 py-1.5 rounded-lg bg-blue-600 hover:bg-blue-500 text-white text-xs font-semibold shadow-md shadow-blue-500/20 transition-colors"
                >
                  <span>Open on GitHub</span>
                  <ExternalLink className="w-3 h-3" />
                </a>
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
}
